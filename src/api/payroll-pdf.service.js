const PDFDocument = require('pdfkit');

function cleanText(value) {
  return String(value ?? '')
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, ' ')
    .trim();
}

function dateOnly(value) {
  return value instanceof Date
    ? value.toISOString().slice(0, 10)
    : String(value ?? '').slice(0, 10);
}

function formatMoney(cents, currency) {
  return new Intl.NumberFormat('en-ZA', {
    style: 'currency',
    currency,
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(Number(cents) / 100);
}

function makePayslipPdf({ payslip }) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 48 });
    const chunks = [];
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.once('error', reject);
    doc.once('end', () => resolve(Buffer.concat(chunks)));

    const left = 48;
    const right = 547;
    const moneyX = 400;
    const moneyWidth = right - moneyX;
    const money = (value) => formatMoney(value, payslip.currency);
    const rule = (y) => doc.moveTo(left, y).lineTo(right, y)
      .lineWidth(0.6).strokeColor('#dce5df').stroke();

    doc.rect(left, 42, 4, 24).fill('#198257');
    doc.font('Helvetica-Bold').fontSize(18).fillColor('#153f32')
      .text(cleanText(payslip.business_name) || 'Business', left + 14, 43, { width: 300 });
    doc.font('Helvetica-Bold').fontSize(17).fillColor('#153f32')
      .text('PAYSLIP', 360, 43, { width: moneyWidth, align: 'right' });

    doc.font('Helvetica-Bold').fontSize(11).fillColor('#27382e')
      .text(`${cleanText(payslip.first_name)} ${cleanText(payslip.last_name)}`, left, 96);
    doc.font('Helvetica').fontSize(9).fillColor('#65736a')
      .text(`Employee number: ${cleanText(payslip.employee_number)}`, left, 114);
    doc.text(`Pay period: ${dateOnly(payslip.period_start)} to ${dateOnly(payslip.period_end)}`, left, 130);
    doc.text(`Pay date: ${dateOnly(payslip.pay_date)}`, left, 146);
    rule(169);

    function row(label, cents, y, { bold = false, color = '#34443a' } = {}) {
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(bold ? 10 : 9).fillColor(color);
      doc.text(label, left, y, { width: 300 });
      doc.text(money(cents), moneyX, y, { width: moneyWidth, align: 'right' });
    }

    doc.font('Helvetica-Bold').fontSize(11).fillColor('#153f32').text('Earnings', left, 187);
    row('Gross pay', payslip.gross_cents, 208, { bold: true });
    rule(229);
    doc.font('Helvetica-Bold').fontSize(11).fillColor('#153f32').text('Employee deductions', left, 247);
    row('PAYE estimate', payslip.paye_cents, 268);
    row('UIF employee contribution', payslip.uif_employee_cents, 286);
    row('Other deductions', payslip.other_deductions_cents, 304);
    rule(326);
    row('Net pay', payslip.net_cents, 345, { bold: true, color: '#153f32' });
    rule(367);

    doc.font('Helvetica-Bold').fontSize(11).fillColor('#153f32').text('Payment tracking', left, 385);
    row('Paid to date', payslip.paid_cents, 406);
    row('Remaining balance', payslip.outstanding_cents, 424, { bold: true });
    rule(446);
    doc.font('Helvetica-Bold').fontSize(11).fillColor('#153f32')
      .text('Employer contributions (not deducted from net pay)', left, 464);
    row('UIF employer contribution', payslip.uif_employer_cents, 485);
    row('SDL estimate', payslip.sdl_cents, 503);

    doc.font('Helvetica').fontSize(8).fillColor('#68776e')
      .text(
        'Payroll figures are estimates based on employer-entered gross pay and configured rules. Verify calculations independently. This document is not a tax certificate or statutory filing.',
        left,
        555,
        { width: right - left, lineGap: 3 }
      );
    doc.font('Helvetica').fontSize(7).fillColor('#98a39b')
      .text('Generated by WorkflowOS', left, 770, { width: right - left, align: 'center' });
    doc.end();
  });
}

module.exports = { makePayslipPdf };
